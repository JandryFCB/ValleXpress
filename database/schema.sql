-- El usuario se genera del nombre de la persona (jcayapa). Si el INSERT ya trae un CUSUARIO se respeta, en minúsculas.
CREATE FUNCTION FNASIGNARUSUARIO() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.CUSUARIO IS NULL OR btrim(NEW.CUSUARIO) = '' THEN
        -- Un solo registro a la vez genera su usuario (evita que dos personas reciban el mismo)
        PERFORM pg_advisory_xact_lock(hashtext('usuarios.usuario'));
        SELECT GENERARUSUARIO(NOMBRES, APELLIDOS) INTO NEW.CUSUARIO
          FROM TPERSONAS WHERE CPERSONA = NEW.CPERSONA AND FHASTA = '2999-12-31 00:00:00-05';
    ELSE
        NEW.CUSUARIO := lower(btrim(NEW.CUSUARIO));
    END IF;
    INSERT INTO TUSUARIOSID (CUSUARIO) VALUES (NEW.CUSUARIO) ON CONFLICT DO NOTHING;
    NEW.CREADOPOR := COALESCE(NEW.CREADOPOR, NEW.CUSUARIO);          -- quien se registra se crea a sí mismo
    RETURN NEW;
END $$;
CREATE TRIGGER TRTUSUARIOSASIGNAR BEFORE INSERT ON TUSUARIOS FOR EACH ROW EXECUTE FUNCTION FNASIGNARUSUARIO();

