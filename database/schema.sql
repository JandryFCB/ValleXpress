-- Asigna el código al insertar: crea la fila ancla y toma su código. Uso: FNASIGNARANCLA('tpedidosid', 'cpedido')
CREATE FUNCTION FNASIGNARANCLA() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_codigo TEXT;
BEGIN
    IF (to_jsonb(NEW) ->> TG_ARGV[1]) IS NULL THEN
        EXECUTE format('INSERT INTO %I DEFAULT VALUES RETURNING %I::TEXT', TG_ARGV[0], TG_ARGV[1]) INTO v_codigo;
        NEW := jsonb_populate_record(NEW, jsonb_build_object(TG_ARGV[1], v_codigo));
    END IF;
    RETURN NEW;
END $$;

