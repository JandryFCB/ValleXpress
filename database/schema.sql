-- Limpieza de logs viejos (los logs crecen sin parar). Ejecutar a diario desde el backend o un cron:
--   SELECT * FROM PURGARLOGS();            -- por defecto: mensajes 30 días, errores resueltos 180 días
CREATE FUNCTION PURGARLOGS(p_diasmensajes INT DEFAULT 30, p_diaserrores INT DEFAULT 180)
RETURNS TABLE (MENSAJESBORRADOS BIGINT, ERRORESBORRADOS BIGINT) LANGUAGE plpgsql AS $$
DECLARE v_m BIGINT; v_e BIGINT;
BEGIN
    DELETE FROM TLOGMENSAJES WHERE CREADOEN < now() - make_interval(days => p_diasmensajes);
    GET DIAGNOSTICS v_m = ROW_COUNT;
    DELETE FROM TLOGERRORES WHERE RESUELTO AND CREADOEN < now() - make_interval(days => p_diaserrores);
    GET DIAGNOSTICS v_e = ROW_COUNT;
    RETURN QUERY SELECT v_m, v_e;
END $$;

-- -----------------------------------------------------------------------------
-- 12. CONTROL DE VERSIONES POR REGISTRO (FDESDE / FHASTA / VERSIONCONTROL)
-- -----------------------------------------------------------------------------
-- Antes de cada UPDATE o DELETE copia la fila anterior a HIST<TABLA> cerrando su
-- vigencia (FHASTA = ahora) y, en la fila vigente, abre la nueva versión:
--     FDESDE = ahora · VERSIONCONTROL + 1 · FHASTA queda como se indique (por defecto 2999-12-31)
-- Para dar de baja un código de catálogo: UPDATE ... SET FHASTA = now().
CREATE FUNCTION FNVERSIONAR() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_cols   TEXT;
    v_sel    TEXT;
    v_ahora  TIMESTAMPTZ := clock_timestamp();
    v_quien  TEXT := NULLIF(current_setting('app.usuario', TRUE), '');
BEGIN
    -- No se versiona si no cambió nada, ni si solo cambiaron columnas "volátiles" (las que el
    -- trigger recibe como argumentos: p. ej. ULTIMACONEXION o la ubicación del repartidor),
    -- que cambian todo el tiempo y llenarían el historial de versiones sin valor.
    IF TG_OP = 'UPDATE' AND (to_jsonb(NEW) - TG_ARGV) = (to_jsonb(OLD) - TG_ARGV) THEN
        RETURN NEW;
    END IF;

    SELECT string_agg(quote_ident(attname), ', ' ORDER BY attnum),
           string_agg(CASE WHEN attname = 'fhasta' THEN '$4' ELSE quote_ident(attname) END, ', ' ORDER BY attnum)
      INTO v_cols, v_sel
      FROM pg_attribute
     WHERE attrelid = TG_RELID AND attnum > 0 AND NOT attisdropped;

    EXECUTE format(
        'INSERT INTO %I (%s, operacion, cambiadopor) SELECT %s, $2, $3 FROM (SELECT ($1).*) x',
        'hist' || TG_TABLE_NAME, v_cols, v_sel)
    USING OLD, TG_OP, v_quien, v_ahora;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    NEW.VERSIONCONTROL := OLD.VERSIONCONTROL + 1;
    NEW.FDESDE         := v_ahora;
    RETURN NEW;
END $$;

-- HISTORIAL EN LA MISMA TABLA (tablas T): antes de cada UPDATE o DELETE inserta una COPIA CERRADA de la fila
-- (FHASTA = ahora, con un ID nuevo) y la fila vigente pasa a la versión siguiente (FDESDE = ahora, VERSIONCONTROL + 1).
--   * Las filas del historial (FHASTA distinto de 2999-12-31) no se pueden modificar: el UPDATE se ignora.
--   * Si el UPDATE no cambia nada, o solo cambia columnas "volátiles" (ULTIMACONEXION, INTENTOSFALLIDOS...),
--     se guarda en la misma fila SIN crear versión.
--   * Quién hizo el cambio: ACTUALIZADOPOR = el usuario del backend (SET LOCAL app.usuario) o, si editas desde
--     Adminer o psql, tu usuario de la base de datos (session_user).
--   * El código (CPERSONA, CUSUARIO...) no se puede cambiar. Argumentos: FNVERSION('columnaclave', 'volatil1', ...)
CREATE FUNCTION FNVERSION() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_ahora     TIMESTAMPTZ := clock_timestamp();
    v_quien     TEXT   := COALESCE(NULLIF(current_setting('app.usuario', TRUE), ''), session_user);
    v_clave     TEXT   := TG_ARGV[0];
    v_volatiles TEXT[] := ARRAY(SELECT unnest(TG_ARGV) OFFSET 1);
    v_cols      TEXT;
    v_sel       TEXT;
BEGIN
    IF OLD.FHASTA <> '2999-12-31 00:00:00-05' THEN
        RETURN NULL;                                          -- historial: no se toca
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF (to_jsonb(NEW) ->> v_clave) IS DISTINCT FROM (to_jsonb(OLD) ->> v_clave) THEN
            RAISE EXCEPTION 'La clave % de % no se puede cambiar (% -> %)', v_clave, TG_TABLE_NAME, to_jsonb(OLD) ->> v_clave, to_jsonb(NEW) ->> v_clave;
        END IF;
        IF (to_jsonb(NEW) - v_volatiles - 'actualizadopor') = (to_jsonb(OLD) - v_volatiles - 'actualizadopor') THEN
            RETURN NEW;                                       -- sin cambios reales: misma versión
        END IF;
    END IF;

    SELECT string_agg(quote_ident(attname), ', ' ORDER BY attnum),
           string_agg(CASE attname
                        WHEN 'fhasta'      THEN '$2'
                        WHEN 'eliminadoen' THEN CASE WHEN TG_OP = 'DELETE' THEN 'COALESCE(x.eliminadoen, $2)' ELSE 'x.eliminadoen' END
                        ELSE 'x.' || quote_ident(attname) END, ', ' ORDER BY attnum)
      INTO v_cols, v_sel
      FROM pg_attribute
     WHERE attrelid = TG_RELID AND attnum > 0 AND NOT attisdropped AND attname <> 'id';

    EXECUTE format('INSERT INTO %I (%s) SELECT %s FROM (SELECT ($1).*) x', TG_TABLE_NAME, v_cols, v_sel)
    USING OLD, v_ahora;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    NEW.ID             := OLD.ID;
    NEW.FDESDE         := v_ahora;
    NEW.FHASTA         := OLD.FHASTA;
    NEW.VERSIONCONTROL := OLD.VERSIONCONTROL + 1;
    NEW.ACTUALIZADOPOR := v_quien;
    RETURN NEW;
END $$;

-- ACTIVARVERSION('TPERSONAS', 'cpersona')                         -> historial en la misma tabla
-- ACTIVARVERSION('TUSUARIOS', 'cusuario', $$'ultimaconexion'$$)    -> con columnas volátiles (entre comillas simples)
CREATE FUNCTION ACTIVARVERSION(p_tabla TEXT, p_clave TEXT, p_volatiles TEXT DEFAULT '') RETURNS VOID LANGUAGE plpgsql AS $$
BEGIN
    EXECUTE format('CREATE UNIQUE INDEX %I ON %I (%I) WHERE FHASTA = %L', 'uq' || lower(p_tabla) || 'vigente', lower(p_tabla), lower(p_clave), '2999-12-31 00:00:00-05');
    EXECUTE format('CREATE INDEX %I ON %I (%I, FDESDE)', 'ix' || lower(p_tabla) || 'historial', lower(p_tabla), lower(p_clave));
    EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION FNVERSION(%s)',
                   'tr' || lower(p_tabla) || 'version', lower(p_tabla),
                   quote_literal(lower(p_clave)) || CASE WHEN p_volatiles = '' THEN '' ELSE ', ' || p_volatiles END);
END $$;

-- Las claves primarias legibles NO se pueden cambiar nunca (otras tablas guardan ese código).
-- Se llama con el nombre de la columna clave:  FNCLAVEFIJA('usuario')
CREATE FUNCTION FNCLAVEFIJA() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF (to_jsonb(NEW) ->> TG_ARGV[0]) IS DISTINCT FROM (to_jsonb(OLD) ->> TG_ARGV[0]) THEN
        RAISE EXCEPTION 'La clave % de % no se puede cambiar (% -> %)',
            TG_ARGV[0], TG_TABLE_NAME, to_jsonb(OLD) ->> TG_ARGV[0], to_jsonb(NEW) ->> TG_ARGV[0];
