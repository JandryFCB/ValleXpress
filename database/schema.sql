-- VUSUARIOS: vista plana de lo VIGENTE (usuario + persona + teléfono principal + foto de perfil).
-- Se puede consultar (SELECT * FROM VUSUARIOS) y también INSERTAR / ACTUALIZAR: los triggers de abajo reparten
-- los datos en TPERSONAS, TUSUARIOS, TPERSONATELEFONOS y TPERSONAIMAGENES, y el historial queda en cada tabla.
CREATE VIEW VUSUARIOS AS
SELECT u.CUSUARIO AS USUARIO, u.CPERSONA, u.CROL AS ROL, u.CESTATUSUARIO,
       p.NOMBRES, p.APELLIDOS, p.EMAIL, t.NUMERO AS TELEFONO,
       p.TIPODOC, p.NUMDOC, p.FECHANAC, p.GENERO, u.CLAVEHASH, i.ARCHIVO AS FOTO,
       p.EMAILVERIF, p.EMAILVERIFEN, COALESCE(t.VERIFICADO, FALSE) AS TELVERIF, t.VERIFICADOEN AS TELVERIFEN,
       u.TERMINOSEN, u.TERMINOSVER, u.IDIOMA, u.ZONAHORARIA, u.ACEPTANOTIF, u.ACEPTAPROMO,
       u.INTENTOSFALLIDOS, u.BLOQUEADOHASTA, u.CLAVECAMBIADAEN, u.ULTIMACONEXION, u.ULTIMAIP,
       (u.CESTATUSUARIO = 'ACT') AS ACTIVO,
       u.FDESDE, u.FHASTA, u.VERSIONCONTROL, u.DATOSEXTRA, u.CREADOEN, u.CREADOPOR, u.ACTUALIZADOPOR, u.ELIMINADOEN
  FROM TUSUARIOS u
  JOIN TPERSONAS p ON p.CPERSONA = u.CPERSONA AND p.FHASTA = '2999-12-31 00:00:00-05'
  LEFT JOIN TPERSONATELEFONOS t ON t.CPERSONA = u.CPERSONA AND t.PRINCIPAL AND t.FHASTA = '2999-12-31 00:00:00-05' AND t.ELIMINADOEN IS NULL
  LEFT JOIN TPERSONAIMAGENES i ON i.CPERSONA = u.CPERSONA AND i.CTIPOIMAGEN = 'PER' AND i.FHASTA = '2999-12-31 00:00:00-05' AND i.ELIMINADOEN IS NULL
 WHERE u.FHASTA = '2999-12-31 00:00:00-05';

CREATE FUNCTION FNVUSUARIOSINSERTAR() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_usuario VARCHAR(30) := NULLIF(lower(btrim(NEW.USUARIO)), '');
    v_persona INTEGER;
    r         VUSUARIOS%ROWTYPE;
BEGIN
    IF v_usuario IS NULL THEN
        PERFORM pg_advisory_xact_lock(hashtext('usuarios.usuario'));
        v_usuario := GENERARUSUARIO(NEW.NOMBRES, NEW.APELLIDOS);
    END IF;

    INSERT INTO TPERSONAS (NOMBRES, APELLIDOS, TIPODOC, NUMDOC, FECHANAC, GENERO, EMAIL, EMAILVERIF, EMAILVERIFEN, CREADOPOR)
    VALUES (NEW.NOMBRES, NEW.APELLIDOS, COALESCE(NEW.TIPODOC, 'CEDULA'), NEW.NUMDOC, NEW.FECHANAC, NEW.GENERO, NEW.EMAIL,
            COALESCE(NEW.EMAILVERIF, FALSE), NEW.EMAILVERIFEN, COALESCE(NEW.CREADOPOR, v_usuario))
    RETURNING CPERSONA INTO v_persona;

    INSERT INTO TUSUARIOS (CUSUARIO, CPERSONA, CROL, CESTATUSUARIO, CLAVEHASH, TERMINOSEN, TERMINOSVER, IDIOMA, ZONAHORARIA,
                           ACEPTANOTIF, ACEPTAPROMO, CLAVECAMBIADAEN, DATOSEXTRA, CREADOPOR)
    VALUES (v_usuario, v_persona, NEW.ROL, CASE WHEN COALESCE(NEW.ACTIVO, TRUE) THEN 'ACT' ELSE 'INA' END, NEW.CLAVEHASH,
            NEW.TERMINOSEN, NEW.TERMINOSVER, COALESCE(NEW.IDIOMA, 'es'), COALESCE(NEW.ZONAHORARIA, 'America/Guayaquil'),
            COALESCE(NEW.ACEPTANOTIF, TRUE), COALESCE(NEW.ACEPTAPROMO, FALSE), NEW.CLAVECAMBIADAEN, NEW.DATOSEXTRA,
            COALESCE(NEW.CREADOPOR, v_usuario));

    IF NEW.TELEFONO IS NOT NULL THEN
        INSERT INTO TPERSONATELEFONOS (CPERSONA, NUMERO, PRINCIPAL, VERIFICADO, VERIFICADOEN, CREADOPOR)
        VALUES (v_persona, NEW.TELEFONO, TRUE, COALESCE(NEW.TELVERIF, FALSE), NEW.TELVERIFEN, v_usuario);
    END IF;
    IF NEW.FOTO IS NOT NULL THEN
        INSERT INTO TPERSONAIMAGENES (CPERSONA, CTIPOIMAGEN, ARCHIVO, CREADOPOR) VALUES (v_persona, 'PER', NEW.FOTO, v_usuario);
    END IF;

    SELECT * INTO r FROM VUSUARIOS WHERE USUARIO = v_usuario;
    RETURN r;
END $$;

CREATE FUNCTION FNVUSUARIOSACTUALIZAR() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    r VUSUARIOS%ROWTYPE;
BEGIN
    IF NEW.USUARIO IS DISTINCT FROM OLD.USUARIO THEN
        RAISE EXCEPTION 'El USUARIO no se puede cambiar (% -> %)', OLD.USUARIO, NEW.USUARIO;
    END IF;

    -- Se actualiza siempre con los valores de NEW: FNVERSION ignora los UPDATE que no cambian nada
    UPDATE TPERSONAS SET NOMBRES = NEW.NOMBRES, APELLIDOS = NEW.APELLIDOS, TIPODOC = NEW.TIPODOC, NUMDOC = NEW.NUMDOC,
           FECHANAC = NEW.FECHANAC, GENERO = NEW.GENERO, EMAIL = NEW.EMAIL, EMAILVERIF = NEW.EMAILVERIF, EMAILVERIFEN = NEW.EMAILVERIFEN
     WHERE CPERSONA = OLD.CPERSONA AND FHASTA = '2999-12-31 00:00:00-05';

    UPDATE TUSUARIOS SET CROL = NEW.ROL, CLAVEHASH = NEW.CLAVEHASH,
           CESTATUSUARIO = CASE WHEN NEW.ACTIVO IS DISTINCT FROM OLD.ACTIVO THEN (CASE WHEN NEW.ACTIVO THEN 'ACT' ELSE 'INA' END) ELSE CESTATUSUARIO END,
           TERMINOSEN = NEW.TERMINOSEN, TERMINOSVER = NEW.TERMINOSVER, IDIOMA = NEW.IDIOMA, ZONAHORARIA = NEW.ZONAHORARIA,
           ACEPTANOTIF = NEW.ACEPTANOTIF, ACEPTAPROMO = NEW.ACEPTAPROMO, INTENTOSFALLIDOS = NEW.INTENTOSFALLIDOS,
           BLOQUEADOHASTA = NEW.BLOQUEADOHASTA, CLAVECAMBIADAEN = NEW.CLAVECAMBIADAEN, ULTIMACONEXION = NEW.ULTIMACONEXION,
           ULTIMAIP = NEW.ULTIMAIP, DATOSEXTRA = NEW.DATOSEXTRA, ELIMINADOEN = NEW.ELIMINADOEN
     WHERE CUSUARIO = OLD.USUARIO AND FHASTA = '2999-12-31 00:00:00-05';

    -- Teléfono principal
    IF NEW.TELEFONO IS DISTINCT FROM OLD.TELEFONO OR NEW.TELVERIF IS DISTINCT FROM OLD.TELVERIF
       OR NEW.TELVERIFEN IS DISTINCT FROM OLD.TELVERIFEN THEN
        IF NEW.TELEFONO IS NULL THEN
            UPDATE TPERSONATELEFONOS SET ELIMINADOEN = now(), PRINCIPAL = FALSE
             WHERE CPERSONA = OLD.CPERSONA AND PRINCIPAL AND ELIMINADOEN IS NULL AND FHASTA = '2999-12-31 00:00:00-05';
        ELSIF EXISTS (SELECT 1 FROM TPERSONATELEFONOS WHERE CPERSONA = OLD.CPERSONA AND PRINCIPAL AND ELIMINADOEN IS NULL AND FHASTA = '2999-12-31 00:00:00-05') THEN
            UPDATE TPERSONATELEFONOS SET NUMERO = NEW.TELEFONO, VERIFICADO = COALESCE(NEW.TELVERIF, FALSE), VERIFICADOEN = NEW.TELVERIFEN
             WHERE CPERSONA = OLD.CPERSONA AND PRINCIPAL AND ELIMINADOEN IS NULL AND FHASTA = '2999-12-31 00:00:00-05';
        ELSE
            INSERT INTO TPERSONATELEFONOS (CPERSONA, NUMERO, PRINCIPAL, VERIFICADO, VERIFICADOEN, CREADOPOR)
            VALUES (OLD.CPERSONA, NEW.TELEFONO, TRUE, COALESCE(NEW.TELVERIF, FALSE), NEW.TELVERIFEN, OLD.USUARIO);
        END IF;
    END IF;

    -- Foto de perfil
    IF NEW.FOTO IS DISTINCT FROM OLD.FOTO THEN
        IF NEW.FOTO IS NULL THEN
            UPDATE TPERSONAIMAGENES SET ELIMINADOEN = now()
             WHERE CPERSONA = OLD.CPERSONA AND CTIPOIMAGEN = 'PER' AND ELIMINADOEN IS NULL AND FHASTA = '2999-12-31 00:00:00-05';
        ELSIF EXISTS (SELECT 1 FROM TPERSONAIMAGENES WHERE CPERSONA = OLD.CPERSONA AND CTIPOIMAGEN = 'PER' AND ELIMINADOEN IS NULL AND FHASTA = '2999-12-31 00:00:00-05') THEN
            UPDATE TPERSONAIMAGENES SET ARCHIVO = NEW.FOTO
             WHERE CPERSONA = OLD.CPERSONA AND CTIPOIMAGEN = 'PER' AND ELIMINADOEN IS NULL AND FHASTA = '2999-12-31 00:00:00-05';
        ELSE
            INSERT INTO TPERSONAIMAGENES (CPERSONA, CTIPOIMAGEN, ARCHIVO, CREADOPOR) VALUES (OLD.CPERSONA, 'PER', NEW.FOTO, OLD.USUARIO);
        END IF;
    END IF;

    SELECT * INTO r FROM VUSUARIOS WHERE USUARIO = OLD.USUARIO;
    RETURN r;
